#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Проверяет, всё ли готово к работе, и говорит, чего не хватает.

    python3 scripts/check.py

Ничего не меняет — только смотрит и подсказывает.
"""
import sys, os, csv, json, datetime as dt

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import workdays as wd
from make_letter import find_fields

BASE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DIR = os.path.join(BASE, '4_План_и_журнал')
ПАПКИ = ['1_Документы_контракта', '2_Шаблоны_писем', '3_Правила_и_регламенты',
         '4_План_и_журнал', '5_Готовые_письма', 'scripts']

ок, замечания = [], []


def да(msg):
    ок.append(msg)


def нет(msg, что_делать=''):
    замечания.append((msg, что_делать))


def проверить_python():
    v = sys.version_info
    if v < (3, 8):
        нет('Python %d.%d устарел' % (v[0], v[1]), 'Установите Python 3.8 или новее с python.org')
    else:
        да('Python %d.%d.%d' % (v[0], v[1], v[2]))


def проверить_папки():
    нету = [p for p in ПАПКИ if not os.path.isdir(os.path.join(BASE, p))]
    if нету:
        нет('Не хватает папок: %s' % ', '.join(нету), 'Создайте их или скачайте пакет заново')
    else:
        да('Все папки на месте')


def проверить_документы():
    d = os.path.join(BASE, '1_Документы_контракта')
    файлы = [f for f in os.listdir(d) if f.lower().endswith(('.docx', '.odt', '.pdf'))] if os.path.isdir(d) else []
    старые = [f for f in os.listdir(d) if f.lower().endswith('.doc')] if os.path.isdir(d) else []
    if not файлы:
        нет('В папке 1_Документы_контракта нет документов',
            'Положите туда контракт, ТЗ и приложения в формате .docx или .odt')
    else:
        да('Документов контракта: %d' % len(файлы))
    if старые:
        нет('Не читаются файлы старого формата .doc: %s' % ', '.join(старые),
            'Откройте в Word и пересохраните как .docx')


def проверить_паспорт():
    p = os.path.join(DIR, 'контракт.json')
    if not os.path.exists(p):
        нет('Нет паспорта контракта', 'Скажите Клоду: «прочитай контракт и ТЗ и заполни паспорт»')
        return None
    try:
        d = json.load(open(p, encoding='utf-8'))
    except ValueError as e:
        нет('Паспорт контракта повреждён: %s' % e, 'Скорее всего при правке пропущена запятая или кавычка')
        return None

    k, s = d.get('контракт', {}), d.get('стороны', {})
    пусто = []
    if not k.get('номер'):
        пусто.append('номер контракта')
    if not k.get('дата_заключения'):
        пусто.append('дата заключения')
    for роль, поля in (('заказчик', ('наименование',)), ('исполнитель', ('наименование', 'подписант', 'должность_подписанта'))):
        for поле in поля:
            if not s.get(роль, {}).get(поле):
                пусто.append('%s: %s' % (роль, поле.replace('_', ' ')))
    if пусто:
        нет('В паспорте не заполнено: %s' % ', '.join(пусто),
            'Эти данные подставляются в письма. Скажите Клоду недостающее, он впишет')
    else:
        да('Паспорт контракта заполнен')

    об = d.get('обязательства', [])
    if not об:
        нет('В паспорте нет обязательств', 'Скажите Клоду: «разбери контракт и ТЗ на обязательства»')
    else:
        да('Обязательств в плане: %d, этапов: %d' % (len(об), len(d.get('этапы', []))))
    return d


def проверить_шаблоны(d):
    if not d:
        return
    без, битые, поля = [], [], set()
    for o in d.get('обязательства', []):
        if o.get('справочно'):
            continue  # обязанности Заказчика — писем по ним мы не готовим
        t = o.get('шаблон')
        if not t:
            без.append(o['id'])
        elif not os.path.exists(os.path.join(BASE, t)):
            битые.append('%s -> %s' % (o['id'], t))
        else:
            поля.update(find_fields(os.path.join(BASE, t)))
    if битые:
        нет('Шаблон указан, но файла нет: %s' % '; '.join(битые),
            'Проверьте имя файла в папке 2_Шаблоны_писем')
    d2 = os.path.join(BASE, '2_Шаблоны_писем')
    сколько = len([f for f in os.listdir(d2) if f.lower().endswith('.docx')]) if os.path.isdir(d2) else 0
    да('Шаблонов писем: %d' % сколько)
    if без:
        нет('Пунктов без шаблона: %d (%s)' % (len(без), ', '.join(без[:8]) + ('…' if len(без) > 8 else '')),
            'Для них письма пишутся по заготовкам. Запросите шаблоны, если они есть')
    авто = {'номер_контракта', 'дата_контракта', 'предмет_контракта', 'цена_контракта', 'заказчик',
            'подписант_заказчика', 'исполнитель', 'подписант_исполнителя', 'должность_подписанта',
            'телефон', 'исполнитель_письма', 'дата', 'сегодня'}
    ручные = sorted(поля - авто)
    if ручные:
        да('Поля, которые указываются при подготовке письма: %s' % ', '.join('{{%s}}' % f for f in ручные))


def проверить_журнал(d):
    p = os.path.join(DIR, 'журнал_событий.csv')
    if not os.path.exists(p):
        нет('Нет журнала событий', 'Файл 4_План_и_журнал/журнал_событий.csv')
        return
    события = 0
    заключен = False
    with open(p, encoding='utf-8-sig') as f:
        for row in csv.reader(f, delimiter=';'):
            if row and row[0].strip() and not row[0].startswith('#') and len(row) > 1 and row[1].strip():
                события += 1
                if row[0].strip() == 'контракт_заключен':
                    заключен = True
    if not заключен:
        нет('В журнале нет даты заключения контракта',
            'Пока её нет, сроки от неё не считаются. Скажите: «контракт заключили такого-то числа»')
    else:
        да('Отмеченных событий в журнале: %d' % события)


def проверить_календарь(d):
    годы = {str(dt.date.today().year)}
    for st in (d or {}).get('этапы', []):
        for поле in ('оказать_до', 'сдать_и_оплатить_до'):
            if st.get(поле):
                годы.add(st[поле][:4])
    текст = open(wd.CAL, encoding='utf-8').read() if os.path.exists(wd.CAL) else ''
    нету = [g for g in sorted(годы) if ('--- %s ---' % g) not in текст]
    if нету:
        нет('В календаре нет данных на %s' % ', '.join(нету),
            'Обновите: python3 scripts/update_calendar.py %s' % ' '.join(нету))
    else:
        да('Производственный календарь покрывает: %s' % ', '.join(sorted(годы)))
    if 'ПРЕДВАРИТЕЛЬНО' in текст:
        нет('В календаре есть предварительные данные (переносы выходных ещё не утверждены)',
            'Ближе к концу года обновите: python3 scripts/update_calendar.py <год>')


def проверить_правки():
    p = os.path.join(BASE, '3_Правила_и_регламенты', 'ПРАВКИ_И_ЗАМЕЧАНИЯ.md')
    if not os.path.exists(p):
        нет('Нет файла с накопленными правками по письмам',
            'Он нужен, чтобы замечания проверяющих не повторялись')
    d = os.path.join(BASE, '3_Правила_и_регламенты')
    сколько = len([f for f in os.listdir(d) if not f.startswith('.')]) - 2 if os.path.isdir(d) else 0
    if сколько <= 0:
        нет('В папке 3_Правила_и_регламенты нет регламентов',
            'Положите туда регламенты и правила оформления писем — формулировки будут точнее')


def main():
    print('Проверка готовности\n')
    проверить_python()
    проверить_папки()
    проверить_документы()
    d = проверить_паспорт()
    проверить_шаблоны(d)
    проверить_журнал(d)
    проверить_календарь(d)
    проверить_правки()

    for m in ок:
        print('  [ок] %s' % m)
    if замечания:
        print('\nТребует внимания:')
        for m, что in замечания:
            print('  [!] %s' % m)
            if что:
                print('      -> %s' % что)
    print('\nПроверок пройдено: %d, замечаний: %d' % (len(ок), len(замечания)))
    if not замечания:
        print('Всё готово к работе.')


if __name__ == '__main__':
    main()
